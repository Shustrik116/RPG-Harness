    public static Icon? Get(string? id) => id is not null && ById.TryGetValue(id.Trim(), out var i) ? i : null;

    private static string Norm(string? s) => (s ?? "").ToLowerInvariant().Replace('ё', 'е');

    /// <summary>
    /// Иконка навыка: явный id из каталога → совпадение слов в названии (весомее) и описании → иконка категории.
    /// Для «врагу» (debuff/attack) эффекты вроде «оглушение» перевешивают общий «удар».
    /// </summary>
    public static Icon Resolve(string? icon, string? name, string? description, string? category)
    {
        if (Get(icon) is { } direct)
        {
            return direct;
        }

        var n = Norm(name);
        var d = Norm(description);
        Icon? best = null;
        var bestScore = 0;
        foreach (var i in All.Where(i => i.Index < 40 || i.Index >= 45))
        {
            var score = 0;
            var words = WordsOf(i);
            foreach (var k in words.Select(Norm).Distinct())
            {
                if (n.Contains(k)) score += k.Length * 3;
                else if (d.Contains(k)) score += k.Length;
            }

            if (score > bestScore)
            {
                best = i;
                bestScore = score;
            }
        }

        return bestScore >= 3 && best is not null ? best : ById[CategoryDefault(category)];
    }

