    public const string Rules = """
        # Правила игры

        > Базовые правила в духе D&D 5e. Мастер дополняет их правилами мира (раздел «Особые правила»).

        ## Проверки
        - **d20 + модификатор** против **Сложности (DC)**; модификатор = (характеристика − 10) / 2 вниз.
        - DC: 5 — очень легко, 10 — легко, 15 — средне, 20 — сложно, 25 — очень сложно, 30 — почти невозможно.
        - Преимущество / помеха: два d20, берём больший / меньший.
        - Степени успеха (`skill_check`): на 10 и больше выше DC — блестящий успех; DC — успех; на 1–3 ниже DC — успех ценой (цель достигнута с осложнением, игрок может отступить); ниже — провал. Натуральная 20 поднимает итог на ступень, натуральная 1 — опускает.

        ## Бой
        - Инициатива: d20 + ЛОВ, бросается один раз в начале боя; `combat_turn` хранит текущего участника и номер раунда.
        - Ход игрока — это его ход в порядке инициативы: в том же ходу отыгрывают спутники и противники, пока раунд не завершится.
        - Атака: d20 + бонус атаки против КБ цели. Натуральная 20 — критическое попадание (кости урона удваиваются), натуральная 1 — промах.
        - Урон: кость оружия + модификатор (СИЛ — ближний бой, ЛОВ — дальний и фехтовальное) + бонусы вещей.
        - Преимущество / помеха: два d20, берём лучший / худший.
        - Спасбросок: d20 + модификатор против DC эффекта. DC навыка = 8 + мастерство + модификатор ключевой характеристики.
        - ХП до 0 — «при смерти»: без сознания; спасброски делает `resolve_death_save`, который хранит счёт (3 успеха — стабилизирован, 3 провала — смерть, натуральная 20 — приходит в себя с 1 ХП).
        - Если герой не может действовать (0 ХП, оглушение, сон, паралич и т.п.) — его ход пропускается, и бой продолжается сам, пока он не сможет ходить снова. Спутники в первую очередь стараются вернуть героя в строй, но добивают врага, если это решает бой прямо сейчас.
        - Смерть героя — сюжетный поворот, а не молчаливый конец.
        - Рядовые враги не владеют ультимативными навыками, воскрешением и легендарной магией.

        ## Навыки, мана и щит
        - Навыки тратят ману: ступень 1 — 2–4, 2 — 4–7, 3 — 7–12, 4 — 12–18, 5 — 18–30. В бою мана сама не восстанавливается.
        - Урон, лечение и щиты навыков считаются в костях мощи К (1d8 на 1–4 ур., 2d8 с 5-го, 3d8 с 10-го…): ступень 1 — 1К, 2 — 1.5К, 3 — 2К, 4 — 3К, 5 — 4К одной цели. Ступень навыка не выше доступной по уровню (1 на 1–4, 2 на 5–8, 3 на 9–12, 4 на 13–16, 5 с 17-го).
        - Категории навыков: атака, поддержка, лечение, очищение, щит, воскрешение, дебаф, утилита. Цели: self / ally / enemy / all-allies / all-enemies.
        - У каждого персонажа не больше 8 навыков. Сильные навыки ограничены: «раз в бой», перезарядка N раундов или редкий расходник.
        - Энергетический щит — временные ХП поверх обычных: урон сначала снимает щит. Щит не складывается (берётся большее значение) и не превышает половину максимального ХП.
        - Воскрешение — крайне редкое и дорогое: навык ступени 4–5, редкий расходник или легендарная вещь; одно на бой, возврат с 1 ХП и дебафом «Слабость» на 2 раунда.

        ## Состояния и эффекты
        - Каждый бафф и дебаф имеет длительность в раундах; `combat_turn` тикает её в конце хода носителя и снимает истёкшие, урон во времени и регенерацию применяет в начале хода. После боя боевые эффекты и щиты спадают.
        - Мораль: тяжело раненый враг, враг без вожака или поредевший отряд проверяют мораль и могут бежать или сдаться; нежить, конструкты и боссы данжа и арки не бегут.
        - Жёсткий контроль (оглушение, сон, заморозка, очарование, страх, замешательство, опутывание, немота) — не дольше 1–2 раундов и с повторным спасброском; после такого контроля существо получает иммунитет к этому типу на 1 раунд.
        - Ослабление: немощь (−2 атака и урон), снижение защиты (−2 КБ), ослепление, уязвимость (+50% получаемого урона), проклятие, замедление.
        - Урон во времени: поджог (1d6 огня), кровотечение (1d4–1d8), отравление (1d4 яда и помеха на проверки ТЕЛ), кислота, некротическая порча.
        - Поддержка: благословение (+1d4 к атакам и спасброскам), ярость, ускорение, регенерация (+1d6 ХП в начале хода), стойкость, уклонение, невидимость, точность, магический доспех (+3 КБ), барьер стихии, очищение.
        - Эффекты одного типа не складываются, если не сказано явно; повторное наложение обновляет длительность.

        ## Стихии и слабости
        - Типы урона: рубящий, колющий, дробящий, огонь, холод, электричество, яд, кислота, некротика, свет, психика, звук, силовое поле.
        - Сопротивление — половина урона, уязвимость — плюс половина, иммунитет — ноль. Слабости и сопротивления существа записывай в Bestiary.md при первой встрече и держи постоянными.

        ## Боссы
        - У элиты и боссов есть шкала стойкости (2–4 сегмента): попадание в слабость, критическое попадание или сильный контроль снимает сегмент; при нуле — «слом» (пропуск хода и +50% получаемого урона на раунд).
        - Боссы данжа и арки получают 1–3 легендарных действия за раунд: атака, перемещение или эффект.

        ## Магия
        - Заклинание тратит ману (1–2 — простое, 3–5 — сильное, 6+ — мощное).
        - Сложность спасброска против заклинания: 8 + 2 + мод характеристики заклинателя.

        ## Отдых
        - Короткий привал (≈1 час, `rest short`): четверть ХП и ману; не больше двух между ночлегами.
        - Ночлег (`rest long`): все ХП и ману, снимаются эффекты «до отдыха», свойства «раз в день» снова доступны, наступает утро. Вне поселения съедается паёк — без еды восстанавливается половина; в диком месте возможна ночная тревога.

        ## Торговля
        - Цены — из лавки торговца (окно торговли) и ориентиров World.md.
        - Торговец охотно берёт товары своего ремесла (примерно за половину цены), смежные — задёшево, остальное не берёт.
        - Харизма героя даёт скидку или надбавку до 15%; торг — проверка ХАР (Убеждение) против DC 12–18.

        ## Опыт и уровни
        - Опыт за победы (средний бой ≈ 80, тяжёлый ≈ 120), задания (20–300) и находчивость (10–40). Новый уровень — каждые 600 опыта; уровни идут и после 20-го (эндгейм).
        - Новый уровень (level_up): ХП и мана по архетипу класса; мастерство, кость мощи К, боевой опыт (+1 КБ на 6, 12, 18…) и максимальная ступень навыков растут сами.
        - Выбор на уровне: новый навык или +1 ступень навыка; на 4, 8, 12, 16, 19 — ещё +2 к характеристикам.
        - Противники считаются по уровню и роли (plan_encounter); опасность регионов указана в World.md.

        ## Особые правила мира
        _Добавь правила, которые делают этот мир особенным._
        """;

