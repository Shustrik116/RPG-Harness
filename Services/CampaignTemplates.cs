    private static string Normalize(string text) => text.Replace("\r", "").Trim();

    /// <summary>Файл — всё ещё нетронутый шаблон (его можно перезаписать целиком без overwrite).</summary>
    public static bool IsUnfilled(string relPath, string content)
    {
        var name = Path.GetFileName(relPath.Replace('\\', '/'));
        var templates = FantasyFiles.Concat(CyberFiles).Concat(ModernFiles)
            .Concat(FantasyFilesEn).Concat(CyberFilesEn).Concat(ModernFilesEn).Where(t => t.File.Equals(name, StringComparison.OrdinalIgnoreCase)).Select(t => t.Content).ToList();
        if (templates.Count == 0)
        {
            return false;
        }

        // Нетронутый шаблон любого сеттинга и языка: так кампания не застрянет, если файл создан до смены темы или языка.
        var normalized = Normalize(content);
        if (templates.Any(t => normalized == Normalize(t)))
        {
            return true;
        }

        if (name.Equals("World.md", StringComparison.OrdinalIgnoreCase) &&
            (normalized.Contains(LegacyWorldMarker) || normalized.Contains(LegacyModernWorldMarker)))
        {
            return true;
        }

        if (name.Equals("Bestiary.md", StringComparison.OrdinalIgnoreCase) && normalized.Contains(LegacyModernBestiaryMarker))
        {
            return true;
        }

        // Старые шаблоны Rules.md: сохранилась заглушка «Особых правил» и прежний блок боя или прежняя таблица опыта.
        return name.Equals("Rules.md", StringComparison.OrdinalIgnoreCase) &&
               normalized.Contains(LegacyRulesPlaceholder) &&
               (normalized.Contains(LegacyRulesCombat) || normalized.Contains(LegacyRulesXp) || normalized.Contains(LegacyRulesRest) ||
                normalized.Contains(LegacyModernRulesMarker));
    }

    /// <summary>Заголовки разделов шаблона — короткая подсказка в сводке мастеру.</summary>
    public static string Outline(string template) =>
        string.Join(" · ", template.Split('\n')
            .Select(l => l.Trim())
            .Where(l => l.StartsWith("## "))
            .Select(l => l[3..]));
