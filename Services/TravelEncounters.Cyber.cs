    private static string NormalizeCyberTerrain(string t)
    {
        if (t.Contains("улиц") || t.Contains("трущоб") || t.Contains("квартал") || t.Contains("street") || t.Contains("район") || t.Contains("slum") || t.Contains("district") || t.Contains("alley")) return "street";
        if (t.Contains("корпор") || t.Contains("башн") || t.Contains("центр") || t.Contains("corporate") || t.Contains("деловой") || t.Contains("tower") || t.Contains("downtown") || t.Contains("corpo")) return "corporate";
        if (t.Contains("пром") || t.Contains("завод") || t.Contains("док") || t.Contains("порт") || t.Contains("склад") || t.Contains("industrial") || t.Contains("factory") || t.Contains("dock") || t.Contains("port") || t.Contains("warehouse")) return "industrial";
        if (t.Contains("пустош") || t.Contains("пустын") || t.Contains("wasteland") || t.Contains("за стен") || t.Contains("бэдленд") || t.Contains("badland") || t.Contains("desert") || t.Contains("waste")) return "wasteland";
        if (t.Contains("метро") || t.Contains("тоннел") || t.Contains("коллектор") || t.Contains("подзем") || t.Contains("канализ") || t.Contains("underground") || t.Contains("metro") || t.Contains("subway") || t.Contains("tunnel") || t.Contains("sewer")) return "underground";
        if (t.Contains("сет") || t.Contains("net") || t.Contains("киберпрост") || t.Contains("матриц") || t.Contains("cyberspace") || t.Contains("matrix")) return "net";
        return "";
    }

