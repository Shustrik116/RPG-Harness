    private static string NormalizeModernTerrain(string t)
    {
        if (t.Contains("город") || t.Contains("улиц") || t.Contains("район") || t.Contains("city") || t.Contains("центр") || t.Contains("town") || t.Contains("street") || t.Contains("district")) return "city";
        if (t.Contains("трасс") || t.Contains("шоссе") || t.Contains("дорог") || t.Contains("автобан") || t.Contains("highway") || t.Contains("road") || t.Contains("freeway") || t.Contains("motorway")) return "highway";
        if (t.Contains("сел") || t.Contains("дерев") || t.Contains("посёл") || t.Contains("посел") || t.Contains("просёл") || t.Contains("rural") || t.Contains("пол") || t.Contains("village") || t.Contains("countryside") || t.Contains("farm") || t.Contains("field")) return "rural";
        if (t.Contains("лес") || t.Contains("гор") || t.Contains("тайг") || t.Contains("степ") || t.Contains("пустын") || t.Contains("wild") || t.Contains("болот") || t.Contains("forest") || t.Contains("mountain") || t.Contains("taiga") || t.Contains("steppe") || t.Contains("desert") || t.Contains("swamp")) return "wild";
        if (t.Contains("пром") || t.Contains("завод") || t.Contains("порт") || t.Contains("склад") || t.Contains("гараж") || t.Contains("industrial") || t.Contains("factory") || t.Contains("port") || t.Contains("warehouse") || t.Contains("garage")) return "industrial";
        if (t.Contains("границ") || t.Contains("блокпост") || t.Contains("таможн") || t.Contains("border") || t.Contains("кордон") || t.Contains("checkpoint") || t.Contains("customs")) return "border";
        return "";
    }

